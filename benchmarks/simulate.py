"""Simulate review logs from a known DSR ground truth.

A simulated student reviews each card near its scheduled interval (with jitter, so
recall probabilities span the whole (0,1) range — essential for identifiability), and the
outcome is drawn Bernoulli(R_true). The grade is consistent with the outcome. Because the
logs are generated by the *true* model, a correct fitter should recover its behaviour.
"""
from __future__ import annotations
import numpy as np
from memora.model import Scheduler


def simulate_logs(params, n_cards=400, n_reviews=8, seed=0,
                  jitter=(0.5, 1.5), request_retention=0.9):
    """Return chronological logs: list of (card_id, grade, elapsed_days, recalled)."""
    rng = np.random.default_rng(seed)
    sched = Scheduler(params)
    logs = []
    for cid in range(n_cards):
        grade0 = int(rng.choice([2, 3, 4], p=[0.2, 0.6, 0.2]))   # varied first impressions
        card = sched.init_card(grade0, now=0.0)
        logs.append((cid, grade0, 0.0, 1))                        # init entry
        last_t = 0.0
        for _ in range(n_reviews):
            interval = sched.next_interval(card, request_retention)
            elapsed = float(interval * rng.uniform(*jitter))
            now = last_t + elapsed
            R = card.retrievability(now)
            recalled = int(rng.random() < R)
            grade = 1 if not recalled else int(rng.choice([3, 4], p=[0.75, 0.25]))
            logs.append((cid, grade, elapsed, recalled))
            card = sched.review(card, grade, now)
            last_t = now
    return logs
